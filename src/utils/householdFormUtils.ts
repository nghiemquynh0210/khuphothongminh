import { Household, HouseholdAuditEntry, Resident, TargetGisItem } from "../types";
import {
  generateDefaultCoordinatesForAddress,
  parseCoordinates as parseGisCoords
} from "./gisUtils";

/**
 * Tìm sổ hộ khẩu theo id hoặc mã sổ (hỗ trợ cả UUID từ DB và mã HK-xxx).
 */
export function findHouseholdByIdOrCode(
  households: Household[],
  idOrCode?: string
): Household | null {
  if (!idOrCode) return null;
  const target = idOrCode.trim();
  return (
    households.find(h => h.id === target) ||
    households.find(h => h.code.trim().toUpperCase() === target.toUpperCase()) ||
    null
  );
}

/**
 * Kiểm tra sổ hộ khẩu đang nằm trong thùng rác lưu trữ (soft-delete).
 */
export function isHouseholdSoftDeleted(household: Household): boolean {
  return Boolean(household.deletedAt);
}

/**
 * Phân tích chuỗi tọa độ thập phân WGS84 (lat, lng) và chuẩn hóa hiển thị.
 */
export function parseGpsPair(
  input: string
): { lat: number; lng: number; formatted: string } | null {
  if (!input) return null;
  const parts = input.split(",");
  if (parts.length !== 2) return null;
  const p1 = parseFloat(parts[0].trim());
  const p2 = parseFloat(parts[1].trim());
  if (Number.isNaN(p1) || Number.isNaN(p2)) return null;

  let lat = p1;
  let lng = p2;
  // Chuẩn hóa thứ tự Vĩ độ / Kinh độ tại Việt Nam
  if (p1 > 100 && p2 < 30) {
    lat = p2;
    lng = p1;
  }
  return { lat, lng, formatted: `${lat.toFixed(6)}, ${lng.toFixed(6)}` };
}

/**
 * Tạo bản ghi nhật ký biến động mới và gắn vào đầu danh sách lịch sử của sổ hộ khẩu.
 */
export function appendHouseholdAuditEntry(
  household: Household,
  action: string,
  actor = "Cán bộ Tư pháp"
): HouseholdAuditEntry[] {
  const existing = household.auditHistory || [];
  const entry: HouseholdAuditEntry = {
    date: new Date().toLocaleString("vi-VN"),
    action,
    actor
  };
  return [entry, ...existing];
}

/**
 * Khôi phục sổ hộ khẩu từ trạng thái lưu trữ (xóa dấu vết soft-delete và ghi nhật ký).
 */
export function restoreSoftDeletedHousehold(
  household: Household,
  actor = "Cán bộ Tư pháp"
): Household {
  const copy: Household = {
    ...household,
    auditHistory: appendHouseholdAuditEntry(
      household,
      "Khôi phục sổ hộ khẩu từ mục lưu trữ",
      actor
    )
  };
  delete copy.deletedAt;
  delete copy.deletedBy;
  return copy;
}

/**
 * Che một phần số CCCD/Định danh theo Nghị định 13/2023/NĐ-CP.
 */
export function maskCitizenId(raw?: string, showFull = false): string {
  if (!raw) return "Chưa cập nhật";
  if (showFull) return raw;
  if (raw.length >= 9) {
    return `${raw.slice(0, 4)} ••• ••• ${raw.slice(-3)}`;
  }
  return raw;
}

/**
 * Tạo đối tượng TargetGisItem cho sổ hộ khẩu, tự động ước tính tọa độ nếu chưa có.
 */
export function buildGisTargetForHousehold(household: Household): {
  target: TargetGisItem;
  resolvedCoordinates: string;
  wasAutoGenerated: boolean;
} {
  let coords = household.coordinates;
  let wasAutoGenerated = false;
  if (!coords || !parseGisCoords(coords)) {
    const autoGeo = generateDefaultCoordinatesForAddress(household.address, household.code);
    coords = autoGeo.dms;
    wasAutoGenerated = true;
  }
  return {
    target: {
      id: household.id,
      type: "household",
      name: `Hộ ${household.ownerName} (${household.code})`,
      address: household.address,
      coordinates: coords,
      navigateRoute: true
    },
    resolvedCoordinates: coords,
    wasAutoGenerated
  };
}

/**
 * Tìm bản ghi Resident tương ứng theo CCCD trong danh sách cư dân.
 */
export function findResidentByCccd(
  residents: Resident[],
  cccd?: string
): Resident | null {
  if (!cccd) return null;
  const clean = cccd.trim();
  return residents.find(r => r.cccd.trim() === clean) || null;
}

