export const isEnterpriseEntity = (b: Business): boolean => {
  if (b.businessType) {
    if (
      [
        "Công ty TNHH",
        "Công ty Cổ phần",
        "Doanh nghiệp tư nhân",
        "Cơ sở kinh doanh khác"
      ].includes(b.businessType)
    ) {
      return true;
    }
    if (b.businessType === "Hộ kinh doanh") return false;
  }
  const nameLower = (b.name || "").toLowerCase();
  const typeLower = (b.type || "").toLowerCase();
  return (
    nameLower.includes("công ty") ||
    nameLower.includes("tnhh") ||
    nameLower.includes("cổ phần") ||
    nameLower.includes("doanh nghiệp") ||
    nameLower.includes("nhà sách") ||
    typeLower.includes("công ty") ||
    Boolean(b.employeeCount && b.employeeCount >= 5 && !b.isAccommodation)
  );
};

export const getEnterpriseScaleLabel = (b: Business): EnterpriseScaleType => {
  if (b.enterpriseScale) return b.enterpriseScale;
  const count = b.employeeCount || 1;
  if (count < 5) return "Siêu nhỏ (< 5 LĐ)";
  if (count <= 20) return "Nhỏ (5 - 20 LĐ)";
  if (count <= 50) return "Vừa (20 - 50 LĐ)";
  return "Lớn (> 50 LĐ)";
};

export const getEnterpriseImage = (ent?: Business | null): string => {
  if (!ent) return ENTERPRISE_DEFAULT_IMAGES[0];
  if (ent.image && typeof ent.image === "string" && ent.image.trim() !== "") {
    return ent.image;
  }
  if (
    ent.images &&
    Array.isArray(ent.images) &&
    ent.images.length > 0 &&
    ent.images[0] &&
    ent.images[0].trim() !== ""
  ) {
    return ent.images[0];
  }
  const hash = (ent.id || ent.name || "DN")
    .split("")
    .reduce((acc, char) => acc + char.charCodeAt(0), 0);
  return ENTERPRISE_DEFAULT_IMAGES[hash % ENTERPRISE_DEFAULT_IMAGES.length];
};

export function findEnterpriseByIdOrCode(
  businesses: Business[],
  idOrCode?: string
): Business | null {
  if (!idOrCode) return null;
  const clean = idOrCode.trim();
  const enterprises = businesses.filter(isEnterpriseEntity);
  return (
    enterprises.find(b => b.id === clean) ||
    enterprises.find(
      b => (b.internalCode || "").trim().toUpperCase() === clean.toUpperCase()
    ) ||
    businesses.find(b => b.id === clean) ||
    null
  );
}

export function buildGisTargetForEnterprise(ent: Business): {
  target: TargetGisItem;
  resolvedCoordinates: string;
  wasAutoGenerated: boolean;
} {
  let coords = ent.coordinates;
  let wasAutoGenerated = false;
  if (!coords || !parseGisCoords(coords)) {
    const autoGeo = generateDefaultCoordinatesForAddress(ent.address, ent.id);
    coords = autoGeo.dms;
    wasAutoGenerated = true;
  }
  return {
    target: {
      id: ent.id,
      type: "enterprise",
      name: ent.name,
      address: ent.address,
      coordinates: coords,
      navigateRoute: true
    },
    resolvedCoordinates: coords,
    wasAutoGenerated
  };
}

export function getLinkedHouseholdForEnterprise(
  b: Business,
  households: Household[]
): Household | undefined {
  if (b.linkedHouseholdCode) {
    return households.find(
      h => h.code.toLowerCase() === b.linkedHouseholdCode?.toLowerCase()
    );
  }
  if (b.address) {
    return households.find(h =>
      b.address.toLowerCase().includes(h.address.toLowerCase())
    );
  }
  return undefined;
}

export function getEnterpriseForeignResidents(
  b: Business,
  residents: Resident[]
): Resident[] {
  return residents.filter(r => {
    const isForeign = r.nationality && r.nationality !== "Việt Nam";
    if (!isForeign) return false;
    if (
      r.workplace &&
      b.name &&
      r.workplace.toLowerCase().includes(b.name.toLowerCase())
    ) {
      return true;
    }
    if (b.linkedHouseholdCode && r.householdId === b.linkedHouseholdCode) {
      return true;
    }
    return false;
  });
}

