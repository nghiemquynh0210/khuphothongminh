export function enterpriseToFormValues(ent: Business): EnterpriseFormValues {
  const validBusinessType: EnterpriseBusinessType =
    ent.businessType === "Công ty Cổ phần" ||
    ent.businessType === "Doanh nghiệp tư nhân" ||
    ent.businessType === "Cơ sở kinh doanh khác"
      ? ent.businessType
      : "Công ty TNHH";

  const validPremisesType: EnterprisePremisesType =
    ent.premisesType === "Nhà phố" ||
    ent.premisesType === "Cửa hàng" ||
    ent.premisesType === "Nhà xưởng" ||
    ent.premisesType === "Ki-ốt" ||
    ent.premisesType === "Địa điểm thuê" ||
    ent.premisesType === "Chung cư / Căn hộ"
      ? ent.premisesType
      : "Văn phòng";

  const empCount = ent.employeeCount || 5;

  return {
    name: ent.name || "",
    internalCode: ent.internalCode || `DN-KP3-${ent.id}`,
    taxCode: ent.taxCode || "",
    businessType: validBusinessType,
    enterpriseScale: getEnterpriseScaleLabel(ent),
    type: ent.type || "Thương mại dịch vụ",
    startDate: ent.startDate || "01/01/2024",
    address: ent.address || "",
    streetArea:
      ent.streetArea ||
      (ent.address?.includes("42")
        ? "Hẻm 42 Lương Định Của"
        : "Mặt tiền Lương Định Của"),
    premisesType: validPremisesType,
    premisesOwner: ent.premisesOwner || "",
    premisesOwnerPhone: ent.premisesOwnerPhone || "",
    linkedHouseholdCode: ent.linkedHouseholdCode || "",
    legalRepresentative: ent.legalRepresentative || ent.owner || "",
    legalRepPhone: ent.legalRepPhone || ent.phone || "",
    legalRepEmail: ent.legalRepEmail || "",
    siteManager: ent.siteManager || ent.owner || "",
    siteManagerPhone: ent.siteManagerPhone || ent.phone || "",
    focalPointName: ent.focalPointName || ent.owner || "",
    focalPointPhone: ent.focalPointPhone || ent.phone || "",
    focalPointRole: ent.focalPointRole || "Đại diện phối hợp",
    employeeCount: empCount,
    localWorkersCount: ent.localWorkersCount ?? Math.floor(empCount / 2),
    temporaryWorkersCount: ent.temporaryWorkersCount ?? Math.ceil(empCount / 2),
    foreignWorkersCount:
      ent.foreignWorkersCount || (ent.foreignWorkers?.length || 0),
    supportNeeds: ent.supportNeeds || [],
    supportNotes: ent.supportNotes || "",
    image: ent.image || ""
  };
}

